def add(a,b):
    return a+b
def subtract(a,b):
    return a-b
def multiply(a,b):
    return a*b
def divide(a,b):
    return a/b
a=float(input("Enter First number:"))
b=float(input("Enter Second number:"))

print("Addition =", add (a,b))
print("Subtract =", subtract (a,b))
print("Multiplication =", multiply (a,b))
print("Division =", divide (a,b))
